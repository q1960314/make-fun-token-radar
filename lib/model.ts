// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every protocol that records no token and is not a wrapped, staked or bridged
// product of a token that already trades. The screen is the watchlist's own rule, applied to the
// whole snapshot instead of only the protocols above the floor: a category in the excluded set, a
// name ending in a version marker, a whole word wrapped / staked / staking in the name, or a name
// beginning with an exchange's name all keep a protocol off the board. The 144 protocols the
// screen leaves out are listed in the dashboard's Screened-out view, with the reason each one
// was left out, so the screen itself can be checked.
//
// Implied value follows only from the snapshot's own figures, and the multiple is earned from
// the snapshot, never picked:
//
//   multiple   = the median market-cap / TVL of the live-token protocols in the same category
//                (at least 3 of them; otherwise the median across every live-token protocol),
//                clamped to [0.01, 3.00]
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + min(chains - 1, 4) x 0.03
//   implied    = max(1, round(tvl_usd x multiple x growthMult x maturity x breadth))
//
// A lending protocol is priced off lending protocols that already trade, not off a flat rate:
// the market's own multiples do the pricing, per category. No protocol name is ever
// special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

